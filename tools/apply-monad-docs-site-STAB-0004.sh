set -Eeuo pipefail

TARGET="publication/site"
RUN_SYNC=1
RUN_BUILD=0

usage() {
  cat <<'USAGE'
Usage: apply-monad-docs-site-STAB-0004.sh [options]

Applies the MDX projection and fresh-source build patch over STAB-0003.

Options:
  --skip-sync   Apply files without running content synchronization.
  --build       Run the production build after applying the patch.
  -h, --help    Show this help.
USAGE
}

while (($#)); do
  case "$1" in
    --skip-sync) RUN_SYNC=0 ;;
    --build) RUN_BUILD=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

if REPO_ROOT=$(git rev-parse --show-toplevel 2>/dev/null); then
  :
else
  REPO_ROOT=$(pwd)
fi
REPO_ROOT=$(cd "$REPO_ROOT" && pwd)
SITE_ROOT="$REPO_ROOT/$TARGET"
MARKER="$SITE_ROOT/.monad-site-bootstrap"

if [[ ! -d "$SITE_ROOT" ]]; then
  echo "ERROR: $TARGET does not exist beneath $REPO_ROOT." >&2
  exit 1
fi

if [[ ! -f "$MARKER" ]]; then
  echo "ERROR: $TARGET is not a recognized Monad publication scaffold." >&2
  exit 1
fi

CURRENT_MARKER=$(head -n 1 "$MARKER" || true)
case "$CURRENT_MARKER" in
  STAB-0003|STAB-0004) ;;
  *)
    echo "ERROR: STAB-0004 expects STAB-0003; found $CURRENT_MARKER." >&2
    exit 1
    ;;
esac

TIMESTAMP=$(date -u +%Y%m%dT%H%M%SZ)
BACKUP_DIR="$REPO_ROOT/.monad/backups/publication-site"
BACKUP_FILE="$BACKUP_DIR/STAB-0004-$TIMESTAMP.tar.gz"
mkdir -p "$BACKUP_DIR"

MANAGED_FILES=(
  publication/site/.monad-site-bootstrap
  publication/site/package.json
  publication/site/REAL-CORPUS-COMPATIBILITY.md
  publication/site/scripts/build.mjs
  publication/site/scripts/typegen.mjs
  publication/site/scripts/content/lib/projection.mjs
  publication/site/tests/unit/projection-mdx-validity.test.ts
  publication/site/tests/unit/build-pipeline.test.ts
)

EXISTING_FILES=()
for path in "${MANAGED_FILES[@]}"; do
  [[ -e "$REPO_ROOT/$path" ]] && EXISTING_FILES+=("$path")
done
if ((${#EXISTING_FILES[@]})); then
  tar -czf "$BACKUP_FILE" -C "$REPO_ROOT" "${EXISTING_FILES[@]}"
  echo "Backup: $BACKUP_FILE"
fi

