#!/usr/bin/env bash
set -Eeuo pipefail

PROGRAM_NAME="$(basename "$0")"
TARGET_RELATIVE="publication/site"
FORCE=0
SKIP_INSTALL=0

usage() {
  cat <<'USAGE'
Bootstrap the Monad documentation publication site.

Usage:
  bootstrap-monad-docs-site.sh [options]

Options:
  --force         Overwrite files owned by this bootstrap script.
                  Unknown files are preserved.
  --skip-install  Create the scaffold without running bun install/typecheck.
  --target PATH   Override the target path relative to the repository root.
  -h, --help      Show this help text.

Environment:
  MONAD_ROOT      Explicit repository root. Otherwise git root or cwd is used.
USAGE
}

log() {
  printf '[%s] %s\n' "$PROGRAM_NAME" "$*"
}

fail() {
  printf '[%s] error: %s\n' "$PROGRAM_NAME" "$*" >&2
  exit 1
}

while (($# > 0)); do
  case "$1" in
    --force)
      FORCE=1
      shift
      ;;
    --skip-install)
      SKIP_INSTALL=1
      shift
      ;;
    --target)
      (($# >= 2)) || fail "--target requires a path"
      TARGET_RELATIVE="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      fail "unknown option: $1"
      ;;
  esac
done

if [[ -n "${MONAD_ROOT:-}" ]]; then
  REPO_ROOT="$(cd "$MONAD_ROOT" && pwd)"
elif git_root="$(git rev-parse --show-toplevel 2>/dev/null)"; then
  REPO_ROOT="$git_root"
else
  REPO_ROOT="$(pwd)"
fi

TARGET="$REPO_ROOT/$TARGET_RELATIVE"
MARKER="$TARGET/.monad-site-bootstrap"

if [[ -d "$TARGET" && ! -f "$MARKER" && $FORCE -ne 1 ]]; then
  fail "$TARGET already exists and is not marked as bootstrap-owned; rerun with --force only after reviewing it"
fi

mkdir -p \
  "$TARGET/app/api/search" \
  "$TARGET/app/system/[[...slug]]" \
  "$TARGET/components" \
  "$TARGET/content/system" \
  "$TARGET/lib" \
  "$TARGET/public" \
  "$TARGET/styles"

write_file() {
  local relative="$1"
  local destination="$TARGET/$relative"
  mkdir -p "$(dirname "$destination")"

  if [[ -e "$destination" && $FORCE -ne 1 ]]; then
    log "preserving existing $relative"
    cat >/dev/null
    return
  fi

  cat >"$destination"
  log "wrote $relative"
}

