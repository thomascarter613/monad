#!/usr/bin/env bash
set -Eeuo pipefail

TARGET="publication/site"
RUN_FORMAT=1
RUN_CHECK=1
RUN_VERIFY=0

usage() {
  cat <<'USAGE'
Usage: apply-monad-docs-site-STAB-0007.sh [options]

Applies the Biome release-gate stabilization patch over STAB-0006.

Options:
  --skip-format     Do not run Biome's safe formatter/fixer after applying files.
  --skip-check      Do not run the Biome quality gate after applying files.
  --verify-release  Run the complete release verification after Biome passes.
  -h, --help        Show this help.
USAGE
}

while (($#)); do
  case "$1" in
    --skip-format) RUN_FORMAT=0 ;;
    --skip-check) RUN_CHECK=0 ;;
    --verify-release) RUN_VERIFY=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

if REPO_ROOT=$(git rev-parse --show-toplevel 2>/dev/null); then :; else REPO_ROOT=$(pwd); fi
REPO_ROOT=$(cd "$REPO_ROOT" && pwd)
SITE_ROOT="$REPO_ROOT/$TARGET"
MARKER="$SITE_ROOT/.monad-site-bootstrap"

if [[ ! -d "$SITE_ROOT" ]]; then
  echo "ERROR: $TARGET does not exist beneath $REPO_ROOT." >&2
  exit 1
fi
if [[ ! -f "$MARKER" ]]; then
  echo "ERROR: $TARGET is not a recognized Monad publication scaffold." >&2
  exit 1
fi

CURRENT_MARKER=$(head -n 1 "$MARKER" || true)
case "$CURRENT_MARKER" in
  STAB-0006|STAB-0007) ;;
  *)
    echo "ERROR: STAB-0007 expects STAB-0006; found $CURRENT_MARKER." >&2
    exit 1
    ;;
esac

TIMESTAMP=$(date -u +%Y%m%dT%H%M%SZ)
BACKUP_DIR="$REPO_ROOT/.monad/backups/publication-site"
BACKUP_FILE="$BACKUP_DIR/STAB-0007-$TIMESTAMP.tar.gz"
mkdir -p "$BACKUP_DIR"

MANAGED_FILES=(
  'publication/site/.monad-site-bootstrap'
  'publication/site/package.json'
  'publication/site/REAL-CORPUS-COMPATIBILITY.md'
  'publication/site/biome.json'
  'publication/site/components/mdx.tsx'
  'publication/site/components/brand/monad-mark.tsx'
  'publication/site/components/building-monad/building-monad-index.tsx'
  'publication/site/components/content/document-relationships.tsx'
  'publication/site/components/discovery/search-workspace.tsx'
  'publication/site/components/discovery/structured-data.tsx'
  'publication/site/scripts/operations/check-security.mjs'
  'publication/site/scripts/operations/verify-publication.mjs'
  'publication/site/scripts/publications/build.mjs'
  'publication/site/tests/unit/content-governance.test.ts'
  'publication/site/tests/unit/discovery-contract.test.ts'
  'publication/site/tests/unit/navigation-manifest.test.ts'
  'publication/site/tests/unit/release-gate-contract.test.ts'
  'publication/site/styles/building-monad.css'
  'publication/site/styles/editions.css'
  'publication/site/styles/exploration.css'
)

EXISTING_FILES=()
for path in "${MANAGED_FILES[@]}"; do
  [[ -e "$REPO_ROOT/$path" ]] && EXISTING_FILES+=("$path")
done
if ((${#EXISTING_FILES[@]})); then
  tar -czf "$BACKUP_FILE" -C "$REPO_ROOT" "${EXISTING_FILES[@]}"
  echo "Backup: $BACKUP_FILE"
fi

PAYLOAD_FILE=$(mktemp)
PAYLOAD_DIR=$(mktemp -d)
