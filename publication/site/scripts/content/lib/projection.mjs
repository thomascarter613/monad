function pathWithoutExtension(value) {
  const extension = extname(value);
  return extension ? value.slice(0, -extension.length) : value;
}

function directNodeInfo(documents, collection, directory) {
  const prefix = `content/${collection}/`;
  const pages = [];
  const folders = new Map();
  for (const document of documents) {
    if (!document.generatedPath.startsWith(prefix)) continue;
    const relative = pathWithoutExtension(document.generatedPath.slice(prefix.length));
    const parts = relative.split('/').filter(Boolean);
    const directoryParts = directory ? directory.split('/') : [];
    if (parts.length <= directoryParts.length) continue;
    if (!directoryParts.every((part, index) => parts[index] === part)) continue;

    const next = parts[directoryParts.length];
    if (parts.length === directoryParts.length + 1) {
      pages.push({ token: next, document });
    } else {
      const existing = folders.get(next) ?? [];
      existing.push(document);
      folders.set(next, existing);
    }
  }
  return { pages, folders };
}

function orderedTokens(collection, directory, pageEntries, folderEntries) {
  const pageTokens = pageEntries
    .sort((left, right) => {
      if (left.token === 'index') return -1;
      if (right.token === 'index') return 1;
      return documentSort(left.document, right.document);
    })
    .map((entry) => entry.token);
  const folderTokens = [...folderEntries.entries()]
    .sort((left, right) => {
      const leftFirst = [...left[1]].sort(documentSort)[0];
      const rightFirst = [...right[1]].sort(documentSort)[0];
      return documentSort(leftFirst, rightFirst) || left[0].localeCompare(right[0]);
    })
    .map(([token]) => token);

  const available = new Set([...pageTokens, ...folderTokens]);
  if (!directory && rootPageOrders[collection]) {
    const ordered = rootPageOrders[collection].filter(
      (token) => token.startsWith('---') || available.has(token),
    );
    const included = new Set(ordered.filter((token) => !token.startsWith('---')));
    const remaining = [...available].filter((token) => !included.has(token)).sort();
    return [...ordered, ...remaining];
  }
  return [...pageTokens, ...folderTokens];
}

function folderTitle(collection, directory) {
  if (!directory) return collectionMetadata[collection]?.title ?? titleize(collection);
  const segment = directory.split('/').at(-1) ?? directory;
  const section = publicationSections
    .flatMap((entry) => entry.children)
    .find((entry) => entry.route.endsWith(`/${segment}`));
  return section?.title ?? titleize(segment);
}

async function writeCollectionMetaTrees(stagingRoot, documents) {
  const collections = [...new Set(documents.map((document) => document.generatedPath.split('/')[1]))];
  for (const collection of collections) {
    const prefix = `content/${collection}/`;
    const directories = new Set(['']);
    for (const document of documents) {
      if (!document.generatedPath.startsWith(prefix)) continue;
      const relative = pathWithoutExtension(document.generatedPath.slice(prefix.length));
      const parts = relative.split('/').filter(Boolean);
      for (let index = 1; index < parts.length; index += 1) {
        directories.add(parts.slice(0, index).join('/'));
      }
    }

    for (const directory of [...directories].sort()) {
      const { pages, folders } = directNodeInfo(documents, collection, directory);
      const tokens = orderedTokens(collection, directory, pages, folders);
      const hasIndex = pages.some((entry) => entry.token === 'index');
      const metadata = collectionMetadata[collection] ?? {
        title: titleize(collection),
        description: `${titleize(collection)} documents.`,
      };
      const targetDirectory = join(stagingRoot, 'content', collection, directory);
      await mkdir(targetDirectory, { recursive: true });
      await writeFile(
        join(targetDirectory, 'meta.json'),
        metaFor(
          folderTitle(collection, directory),
          directory ? `${folderTitle(collection, directory)} documents.` : metadata.description,
          tokens,
          hasIndex,
        ),
        'utf8',
      );
    }
  }
}

export function createNavigationManifest(documents, generatedAt) {
  const availableRoutes = new Set([
    '/',
    '/start',
    '/system',
    ...documents.map((document) => document.route),
  ]);
  const routes = publicRouteCatalog().map((route) => {
    const routeDocuments = documents.filter(
      (document) =>
        document.route === route.route || document.route.startsWith(`${route.route}/`),
    );
    return {
      ...route,
      available: availableRoutes.has(route.route) || routeDocuments.length > 0,
      documentCount: routeDocuments.filter((document) => !document.synthetic).length,
    };
  });

  return {
    schemaVersion: 1,
    informationArchitectureVersion,
    generatedAt,
    routePolicy,
    routes,
    readingPaths: readingPaths.map((path) => ({
      ...path,
      steps: path.steps.map((step) => ({
        ...step,
        available: availableRoutes.has(step.route),
      })),
    })),
  };
}

function contentReport(registry) {
  const lines = [
    '# Monad publication content report',
    '',
    `Generated: ${registry.generatedAt}`,
    '',
    `- Contract: ${registry.contractVersion}`,
    `- Canonical documents: ${registry.canonicalDocumentCount}`,
    `- Synthetic pages: ${registry.syntheticDocumentCount}`,
    `- Series: ${registry.series.length}`,
    `- Redirects: ${registry.redirects.length}`,
    `- Warnings: ${registry.warningCount}`,
    `- Errors: ${registry.errorCount}`,
    '',
    '## Issues',
    '',
  ];

  if (registry.issues.length === 0) {
    lines.push('No validation issues.');
  } else {
    for (const entry of registry.issues) {
      const location = entry.canonicalPath ? ` — \`${entry.canonicalPath}\`` : '';
      lines.push(`- **${entry.severity.toUpperCase()} ${entry.code}**${location}: ${entry.message}`);
    }
  }

  lines.push('', '## Redirects', '');
  if (registry.redirects.length === 0) lines.push('No route aliases are registered.');
  for (const redirect of registry.redirects) {
    lines.push(`- \`${redirect.source}\` → \`${redirect.destination}\` (${redirect.id})`);
  }

  return `${lines.join('\n')}\n`;
}

export async function writeProjection(siteRoot, documents, registry) {
  const generatedRoot = join(siteRoot, '.generated');
  const stagingRoot = join(siteRoot, `.generated.staging-${process.pid}`);
  await rm(stagingRoot, { recursive: true, force: true });
  await mkdir(join(stagingRoot, 'content'), { recursive: true });

  for (const document of documents) {
    const targetPath = join(stagingRoot, document.generatedPath);
    await mkdir(dirname(targetPath), { recursive: true });
    await writeFile(targetPath, createGeneratedDocument(document), 'utf8');
  }

  await writeCollectionMetaTrees(stagingRoot, documents);

  const navigation = createNavigationManifest(documents, registry.generatedAt);
  const buildingMonad = buildBuildingMonadManifest(documents, registry.generatedAt);
  const exploration = buildExplorationManifest(registry);
  const discovery = buildDiscoveryManifest(documents, registry.generatedAt);
  const editions = buildEditionManifest(documents, registry.generatedAt);
  await mkdir(join(stagingRoot, 'registry'), { recursive: true });
  await writeFile(
    join(stagingRoot, 'registry', 'documents.json'),
    `${JSON.stringify(registry, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'redirects.json'),
    `${JSON.stringify(registry.redirects, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'series.json'),
    `${JSON.stringify(registry.series, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'relationships.json'),
    `${JSON.stringify(
      registry.documents
        .filter((document) => !document.synthetic)
        .map(({ id, route, relationships }) => ({ id, route, relationships })),
      null,
      2,
    )}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'navigation.json'),
    `${JSON.stringify(navigation, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'reading-paths.json'),
    `${JSON.stringify(navigation.readingPaths, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'building-monad.json'),
    `${JSON.stringify(buildingMonad, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'exploration.json'),
    `${JSON.stringify(exploration, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'discovery.json'),
    `${JSON.stringify(discovery, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'registry', 'editions.json'),
    `${JSON.stringify(editions, null, 2)}\n`,
    'utf8',
  );
  await mkdir(join(stagingRoot, 'reports'), { recursive: true });
  await writeFile(join(stagingRoot, 'reports', 'content-report.md'), contentReport(registry), 'utf8');
  await writeFile(
    join(stagingRoot, 'README.md'),
    '# Generated Monad publication content\n\nThis directory is disposable. Run `bun run content:sync` to rebuild it from canonical repository documents. The document registry and information architecture are versioned independently from the canonical Markdown.\n',
    'utf8',
  );

  await rm(generatedRoot, { recursive: true, force: true });
  await rename(stagingRoot, generatedRoot);
}
