export function generatedRelativePath(document) {
  const extension = '.mdx';
  const prefix = document.source.generatedPrefix;
  const slugPath = document.slug.length > 0 ? document.slug.join('/') : 'index';
  return normalizePath(
    posix.join(
      'content',
      document.source.generatedCollection,
      prefix,
      `${slugPath}${extension}`,
    ),
  );
}

function normalizeHeading(value) {
  return value
    .replace(/[`*_~]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

export function stripLeadingTitleHeading(body, title) {
  const lines = body.replace(/^\uFEFF/, '').split('\n');
  const firstContentIndex = lines.findIndex((line) => line.trim().length > 0);
  if (firstContentIndex < 0) return body;

  const match = lines[firstContentIndex].match(/^#\s+(.+?)\s*#*\s*$/);
  if (!match || normalizeHeading(match[1]) !== normalizeHeading(title)) return body;

  lines.splice(firstContentIndex, 1);
  if (lines[firstContentIndex]?.trim() === '') lines.splice(firstContentIndex, 1);
  return lines.join('\n').trimStart();
}

export function createGeneratedDocument(document) {
  const frontmatter = {
    title: document.title,
    description: document.description,
    id: document.id,
    kind: document.kind,
    family: document.family,
    status: document.status,
    lifecycle: document.lifecycle,
    canonicalPath: document.canonicalPath,
    sourceRoot: document.sourceRoot,
    sourceHash: document.sourceHash,
    generated: true,
    synthetic: document.synthetic,
    aliases: document.aliases ?? [],
    series: document.seriesInfo,
    tags: document.tags,
    references: document.references,
    referencedBy: document.referencedBy ?? [],
    related: document.related,
    relationships: document.relationships ?? { outgoing: [], incoming: [] },
    publication: document.publication,
    repository: document.repository,
  };

  const notice = document.synthetic
    ? '<!-- Generated registry/index page. Do not edit this file directly. -->'
    : `<!-- Generated from ${document.canonicalPath}. Do not edit this projection. -->`;

  const projectedBody = transformDocumentPresentation(
    stripLeadingTitleHeading(document.body, document.title),
  );

  return `${serializeFrontmatter(frontmatter)}${notice}\n\n${projectedBody.trim()}\n`;
}

