import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, join, posix } from 'node:path';
import { serializeFrontmatter } from './frontmatter.mjs';
import { normalizePath, sha256 } from './normalize.mjs';

export function generatedRelativePath(document) {
  const extension = ['.md', '.mdx'].includes(extname(document.relativePath).toLowerCase())
    ? extname(document.relativePath).toLowerCase()
    : '.md';
  const prefix = document.source.generatedPrefix;
  const slugPath = document.slug.length > 0 ? document.slug.join('/') : 'index';
  return normalizePath(posix.join('content', document.source.generatedCollection, prefix, `${slugPath}${extension}`));
}

export function createGeneratedDocument(document) {
  const frontmatter = {
    title: document.title,
    description: document.description,
    id: document.id,
    kind: document.kind,
    status: document.status,
    canonicalPath: document.canonicalPath,
    sourceRoot: document.sourceRoot,
    sourceHash: document.sourceHash,
    generated: true,
    synthetic: document.synthetic,
    series: document.series,
    seriesPosition: document.seriesPosition,
    tags: document.tags,
    references: document.references,
    related: document.related,
  };

  const notice = document.synthetic
    ? '<!-- Generated collection index. Do not edit this file directly. -->'
    : `<!-- Generated from ${document.canonicalPath}. Do not edit this projection. -->`;

  return `${serializeFrontmatter(frontmatter)}${notice}\n\n${document.body.trim()}\n`;
}

function syntheticDocument({
  id,
  title,
  description,
  route,
  slug,
  generatedPath,
  body,
  sourceRoot = '@generated',
}) {
  return {
    id,
    title,
    description,
    kind: 'collection-index',
    status: 'published',
    route,
    slug,
    canonicalPath: `@generated/${id.toLowerCase()}`,
    sourceRoot,
    sourceHash: sha256(body),
    generatedPath,
    synthetic: true,
    tags: [],
    references: [],
    related: {},
    body,
    source: null,
    relativePath: 'index.mdx',
  };
}

function listBody(title, description, documents) {
  const sorted = [...documents].sort((left, right) => {
    const leftPosition = left.seriesPosition ?? Number.MAX_SAFE_INTEGER;
    const rightPosition = right.seriesPosition ?? Number.MAX_SAFE_INTEGER;
    if (leftPosition !== rightPosition) return leftPosition - rightPosition;
    return left.title.localeCompare(right.title);
  });

  const lines = [description, ''];
  if (sorted.length === 0) {
    lines.push(
      '> No canonical documents have been discovered for this collection yet.',
      '',
      'Add Markdown beneath the configured repository source directory, then run `bun run content:sync`.',
    );
  } else {
    lines.push('## Documents', '');
    for (const document of sorted) {
      lines.push(`- [${document.id} — ${document.title}](${document.route})`);
    }
  }
  return lines.join('\n');
}

export function createSyntheticIndexes(documents, sources) {
  const synthetic = [];

  for (const source of sources) {
    const sourceDocuments = documents.filter((document) => document.source.key === source.key);
    const hasRootDocument = sourceDocuments.some((document) => document.slug.length === 0);
    if (hasRootDocument) continue;

    const prefixSegments = source.generatedPrefix ? source.generatedPrefix.split('/') : [];
    const generatedPath = normalizePath(
      posix.join('content', source.generatedCollection, source.generatedPrefix, 'index.mdx'),
    );
    const body = listBody(source.title, source.description, sourceDocuments);

    synthetic.push(
      syntheticDocument({
        id: `COLLECTION-${source.key.toUpperCase().replaceAll('-', '_')}`,
        title: source.title,
        description: source.description,
        route: source.routeBase,
        slug: prefixSegments,
        generatedPath,
        body,
      }),
    );
  }

  const artifactDocuments = documents.filter(
    (document) => document.source.generatedCollection === 'artifacts',
  );
  const artifactBody = [
    'Normative and historical engineering artifacts produced while designing and building Monad.',
    '',
    '## Collections',
    '',
    '- [Architecture Decisions](/artifacts/decisions)',
    '- [Specifications](/artifacts/specifications)',
    '',
    `The current projection contains ${artifactDocuments.length} canonical artifact document${artifactDocuments.length === 1 ? '' : 's'}.`,
  ].join('\n');

  synthetic.push(
    syntheticDocument({
      id: 'COLLECTION-ARTIFACTS',
      title: 'Artifacts',
      description: 'Specifications, decisions, and other durable Monad engineering artifacts.',
      route: '/artifacts',
      slug: [],
      generatedPath: 'content/artifacts/index.mdx',
      body: artifactBody,
    }),
  );

  return synthetic;
}

function metaFor(title, description) {
  return `${JSON.stringify({ title, description }, null, 2)}\n`;
}

export async function writeProjection(siteRoot, documents, registry) {
  const generatedRoot = join(siteRoot, '.generated');
  const stagingRoot = join(siteRoot, `.generated.staging-${process.pid}`);
  await rm(stagingRoot, { recursive: true, force: true });
  await mkdir(join(stagingRoot, 'content'), { recursive: true });

  for (const document of documents) {
    const targetPath = join(stagingRoot, document.generatedPath);
    await mkdir(dirname(targetPath), { recursive: true });
    await writeFile(targetPath, createGeneratedDocument(document), 'utf8');
  }

  await writeFile(
    join(stagingRoot, 'content', 'building-monad', 'meta.json'),
    metaFor(
      'Building Monad',
      'The chronological engineering narrative documenting how Monad is designed and built.',
    ),
    'utf8',
  );
  await mkdir(join(stagingRoot, 'content', 'system', 'architecture'), { recursive: true });
  await writeFile(
    join(stagingRoot, 'content', 'system', 'architecture', 'meta.json'),
    metaFor('Architecture', 'Architecture descriptions and system views for Monad.'),
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'content', 'artifacts', 'meta.json'),
    metaFor('Artifacts', 'Specifications and durable engineering records.'),
    'utf8',
  );
  await mkdir(join(stagingRoot, 'content', 'artifacts', 'decisions'), { recursive: true });
  await writeFile(
    join(stagingRoot, 'content', 'artifacts', 'decisions', 'meta.json'),
    metaFor('Architecture Decisions', 'Monad architecture decision records.'),
    'utf8',
  );
  await mkdir(join(stagingRoot, 'content', 'artifacts', 'specifications'), { recursive: true });
  await writeFile(
    join(stagingRoot, 'content', 'artifacts', 'specifications', 'meta.json'),
    metaFor('Specifications', 'Normative Monad specifications.'),
    'utf8',
  );

  await mkdir(join(stagingRoot, 'registry'), { recursive: true });
  await writeFile(
    join(stagingRoot, 'registry', 'documents.json'),
    `${JSON.stringify(registry, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    join(stagingRoot, 'README.md'),
    '# Generated Monad publication content\n\nThis directory is disposable. Run `bun run content:sync` to rebuild it from canonical repository documents.\n',
    'utf8',
  );

  await rm(generatedRoot, { recursive: true, force: true });
  await rename(stagingRoot, generatedRoot);
}
