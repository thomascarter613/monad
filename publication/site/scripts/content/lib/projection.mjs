function metaFor(title, description, pages, hasIndex = false) {
  const metadata = { title, description };
  if (pages) metadata.pages = pages;
  if (hasIndex) metadata.pagesIndex = 'index';
  return `${JSON.stringify(metadata, null, 2)}\n`;
}

