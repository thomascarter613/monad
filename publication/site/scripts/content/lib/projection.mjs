function documentSort(left, right) {
  const leftPosition = left.seriesPosition ?? left.seriesInfo?.position ?? Number.MAX_SAFE_INTEGER;
  const rightPosition = right.seriesPosition ?? right.seriesInfo?.position ?? Number.MAX_SAFE_INTEGER;
  if (leftPosition !== rightPosition) return leftPosition - rightPosition;
  const idOrder = left.id.localeCompare(right.id, undefined, { numeric: true });
  return idOrder || left.title.localeCompare(right.title);
}

function listBody(description, documents) {
  const sorted = [...documents].sort(documentSort);
  const lines = [description, ''];
  if (sorted.length === 0) {
    lines.push(
      '> No canonical documents have been discovered for this collection yet.',
      '',
      'Add Markdown beneath the configured repository source directory, then run `bun run content:sync`.',
    );
  } else {
    lines.push('## Documents', '');
    for (const document of sorted) {
      const status = document.status ? ` · ${document.status}` : '';
      lines.push(`- [${document.id} — ${document.title}](${document.route})${status}`);
    }
  }
  return lines.join('\n');
}

function registryBody(documents, issues) {
  const canonical = documents.filter((document) => !document.synthetic);
  const lines = [
    'The publication registry is generated from canonical Monad documents. It records stable identity, lifecycle, public routes, aliases, series membership, and document relationships.',
    '',
    `**Canonical documents:** ${canonical.length}  `,
    `**Validation warnings:** ${issues.filter((entry) => entry.severity === 'warning').length}  `,
    `**Validation errors:** ${issues.filter((entry) => entry.severity === 'error').length}`,
    '',
    '## Documents',
    '',
    '| Identifier | Kind | Status | Family | Canonical source |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const document of [...canonical].sort((left, right) => left.id.localeCompare(right.id))) {
    lines.push(
      `| [${document.id}](${document.route}) | ${document.kind} | ${document.status} | ${document.family} | \`${document.canonicalPath}\` |`,
    );
  }

  lines.push(
    '',
    '## Machine-readable forms',
    '',
    '- [`/api/registry`](/api/registry)',
    '- [`/api/navigation`](/api/navigation)',
    '- `.generated/registry/documents.json`',
    '- `.generated/registry/navigation.json`',
  );
  return lines.join('\n');
}

function relationshipsBody(documents) {
  const canonical = documents.filter((document) => !document.synthetic);
  const edges = canonical.flatMap((document) =>
    (document.relationships?.outgoing ?? []).map((edge) => ({ source: document, edge })),
  );
  const lines = [
    'This index exposes validated outgoing and incoming relationships between Monad documents.',
    '',
    `**Documents with incoming links:** ${canonical.filter((document) => document.relationships?.incoming?.length > 0).length}  `,
    `**Validated directed relationships:** ${edges.length}`,
    '',
  ];

  if (edges.length === 0) {
    lines.push('> No validated document relationships have been discovered yet.');
    return lines.join('\n');
  }

  lines.push(
    '## Relationship edges',
    '',
    '| Source | Relationship | Target | Provenance |',
    '| --- | --- | --- | --- |',
  );
  for (const { source, edge } of edges.sort(
    (left, right) =>
      left.source.id.localeCompare(right.source.id) ||
      left.edge.kind.localeCompare(right.edge.kind) ||
      left.edge.id.localeCompare(right.edge.id),
  )) {
    lines.push(
      `| [${source.id}](${source.route}) | ${edge.kind} | [${edge.id}](${edge.route}) | ${edge.explicit ? 'frontmatter' : 'body reference'} |`,
    );
  }
  return lines.join('\n');
}

function seriesBody(series) {
  const lines = [
    'Series provide ordered reading paths across the chronological journal and governed document families.',
    '',
  ];
  if (series.length === 0) {
    lines.push('> No document series have been discovered yet.');
    return lines.join('\n');
  }

  for (const entry of series) {
    lines.push(
      `## ${entry.key}`,
      '',
      `${entry.documentCount} document(s); declared or inferred total: ${entry.total}.`,
      '',
    );
    for (const document of entry.documents) {
      const position = document.position ? `${document.position} of ${entry.total}` : 'unpositioned';
      lines.push(
        `- **${position}:** [${document.id} — ${document.title}](${document.route}) · ${document.status}`,
      );
    }
    lines.push('');
  }
  return lines.join('\n');
}

function projectStatusBody(documents, issues) {
  const canonical = documents.filter((document) => !document.synthetic);
  const byStatus = new Map();
  const byKind = new Map();
  for (const document of canonical) {
    byStatus.set(document.status, (byStatus.get(document.status) ?? 0) + 1);
    byKind.set(document.kind, (byKind.get(document.kind) ?? 0) + 1);
  }

  const lines = [
    'A generated operational snapshot of the documentation corpus and its governance state.',
    '',
    `**Canonical documents:** ${canonical.length}  `,
    `**Validation warnings:** ${issues.filter((entry) => entry.severity === 'warning').length}  `,
    `**Validation errors:** ${issues.filter((entry) => entry.severity === 'error').length}`,
    '',
    '## By lifecycle status',
    '',
  ];
  if (byStatus.size === 0) lines.push('No canonical documents are currently registered.');
  for (const [status, count] of [...byStatus.entries()].sort()) lines.push(`- **${status}:** ${count}`);

  lines.push('', '## By document kind', '');
  for (const [kind, count] of [...byKind.entries()].sort()) lines.push(`- **${kind}:** ${count}`);

  lines.push(
    '',
    '## Operational indexes',
    '',
    '- [Document registry](/artifacts/registry)',
    '- [Series progress](/artifacts/series)',
    '- [Relationship graph](/artifacts/relationships)',
    '- [Build log](/project/build-log)',
  );
  return lines.join('\n');
}

function roadmapBody(documents, series) {
  const canonical = documents.filter((document) => !document.synthetic);
  const openDocuments = canonical.filter((document) => ['draft', 'proposed'].includes(document.status));
  const incompleteSeries = series.filter((entry) => entry.documentCount < entry.total);
  const lines = [
    'This roadmap is derived from governed document status and declared series totals. It is a documentation signal, not a replacement for the implementation backlog.',
    '',
    '## Open governed documents',
    '',
  ];

  if (openDocuments.length === 0) lines.push('No draft or proposed documents are currently registered.');
  for (const document of openDocuments.sort(documentSort)) {
    lines.push(`- [${document.id} — ${document.title}](${document.route}) · ${document.status}`);
  }

  lines.push('', '## Incomplete series', '');
  if (incompleteSeries.length === 0) lines.push('No series declares positions beyond the documents currently present.');
  for (const entry of incompleteSeries) {
    lines.push(
      `- [${entry.key}](/artifacts/series): ${entry.documentCount} of ${entry.total} registered`,
    );
  }
  return lines.join('\n');
}

